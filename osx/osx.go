package osx

import "runtime"

/* ----------------------------------------------------------------
 *                       G L O B A L S
 *-----------------------------------------------------------------*/

var (
	EOL string // OS-specific line terminator: Windows \r\n, else \n
)

/* ----------------------------------------------------------------
 *                     I N I T I A L I Z E R
 *-----------------------------------------------------------------*/

func init() {
	if runtime.GOOS == "windows" {
		EOL = "\r\n"
	} else {
		EOL = "\n"
	}
}

